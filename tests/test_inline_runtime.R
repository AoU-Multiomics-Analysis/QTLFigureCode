# Check that notebook computation cannot use saved-object or overlay shortcuts.
previous <- Sys.getenv(c("QTL_INPUT_ROOT", "QTL_SOURCE_ROOT", "QTL_PAPER_ROOT", "QTL_PREP_ROOT"))
root <- tempfile("inline input ")
dir.create(root)
writeLines("source", file.path(root, "input.tsv"))
saveRDS(list(old = TRUE), file.path(root, "saved.rds"))
overlay <- file.path(root, "prepared")
dir.create(file.path(overlay, "paper"), recursive = TRUE)
writeLines("stale derived data", file.path(overlay, "paper", "input.tsv"))
Sys.setenv(QTL_INPUT_ROOT = root, QTL_SOURCE_ROOT = root, QTL_PAPER_ROOT = root, QTL_PREP_ROOT = overlay)
env <- new.env(parent = globalenv())
sys.source("notebooks/current/00_setup.R", envir = env)
stopifnot(identical(readLines(env$paper_file("input.tsv")), "source"))
writeLines("changed source", file.path(root, "input.tsv"))
changed <- tryCatch({env$paper_file("input.tsv"); ""}, error = conditionMessage)
stopifnot(grepl("Input changed", changed, fixed = TRUE))
error <- tryCatch({env$source_file("saved.rds"); ""}, error = conditionMessage)
stopifnot(grepl("Saved RDS", error, fixed = TRUE))
sys.source("notebooks/current/analysis_runtime.R", envir = env)
cache <- env$prep_result_runtime("Fig3", envir = env)
stopifnot(length(as.list(cache)) == 0L)
computations <- 0L
first <- env$build_or_cache("example", {computations <- computations + 1L; 7L})
second <- env$build_or_cache("example", {computations <- computations + 1L; 8L})
stopifnot(first == 7L, second == 7L, computations == 1L)
fresh <- new.env(parent = globalenv())
sys.source("notebooks/current/00_setup.R", envir = fresh)
sys.source("notebooks/current/analysis_runtime.R", envir = fresh)
fresh$prep_result_runtime("Fig3", envir = fresh)
stopifnot(fresh$build_or_cache("example", 9L) == 9L)
stopifnot(identical(list.files(root, recursive = TRUE), c("input.tsv", "prepared/paper/input.tsv", "saved.rds")))
for (name in names(previous)) if (nzchar(previous[[name]])) do.call(Sys.setenv, setNames(list(previous[[name]]), name)) else Sys.unsetenv(name)
unlink(root, recursive = TRUE)
message("Inline runtime checks passed: source inputs, no saved RDS, and session-only memoization.")
